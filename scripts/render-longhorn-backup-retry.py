#!/usr/bin/env python3
"""Render the source-controlled backup retry program as a GitOps ConfigMap."""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'config/longhorn/backup_retry.py'
target = ROOT / 'config/longhorn/manifests/backup-retry-configmap.yaml'
body = ''.join(('    ' + line if line else '') + '\n'
               for line in source.read_text().rstrip('\n').split('\n'))
target.write_text('''# Generated by scripts/render-longhorn-backup-retry.py; edit config/longhorn/backup_retry.py.
apiVersion: v1
kind: ConfigMap
metadata:
  name: longhorn-backup-retry
  namespace: longhorn-system
data:
  backup_retry.py: |
''' + body)
